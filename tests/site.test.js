const {test} = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');

test('website, dashboard, authenticated publishing and uploaded media', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'likitha-'));
  const legacyContent = {...require('../views/defaults.json')};
  delete legacyContent.staffCards;
  delete legacyContent.boardCards;
  legacyContent.teamCards = legacyContent.teamCards.map((card,i)=>({...card,title:'Existing member '+(i+1)}));
  const published = path.join(directory, 'published');
  await fs.mkdir(published);
  await fs.writeFile(path.join(published, '00000000000000000000-legacy.json'), JSON.stringify(legacyContent));
  process.env.CMS_DATA_DIR = directory;
  process.env.CMS_DEV_SETUP = '1';
  delete process.env.CMS_ADMIN_CREDENTIALS;
  delete process.env.VERCEL;
  delete process.env.NODE_ENV;
  const server = http.createServer(require('../server'));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await fs.rm(directory,{recursive:true}); });
  const base = 'http://127.0.0.1:' + server.address().port;
  let cookie, csrf;
  const post = (endpoint,data) => fetch(base+'/api/admin/'+endpoint,{method:'POST',headers:{
    'content-type':'application/json', origin:base, cookie:cookie || '', 'x-csrf-token':csrf || ''
  },body:JSON.stringify(data)});
  for (const endpoint of ['/','/dashboard','/dashboard/team','/dashboard/clients','/dashboard/testimonials','/about-us','/team','/projects','/clients','/testimonials','/services/athletic-track','/logo.png','/healthz']) {
    assert.equal((await fetch(base+endpoint)).status,200,endpoint);
  }
  const teamBefore = await (await fetch(base+'/team')).text();
  const [managementAndBoard, staff] = teamBefore.split('<h2 id="team-heading">Team</h2>');
  const [management, board] = managementAndBoard.split('<h2 id="board-heading">Board Members</h2>');
  assert.equal((board.match(/<figure class="feature-box about-photo">/g) || []).length,3);
  assert.match(board, /Board member 3/);
  assert.equal((management.match(/<figure class="feature-box about-photo">/g) || []).length,6);
  assert.match(management, /Existing member 6/);
  assert.equal((staff.match(/<figure class="feature-box about-photo">/g) || []).length,3);
  assert.match(teamBefore, /<a href="\/about-us">About us<\/a><a href="\/team" aria-current="page">Team<\/a>/);
  assert.equal((await fetch(base+'/services/missing')).status,404);
  assert.equal((await fetch(base+'/api/services?category=unknown')).status,400);
  assert.equal((await (await fetch(base+'/api/services?q=pool')).json()).count,1);
  assert.equal((await fetch(base+'/api/admin/content')).status,401);
  const sitemap = await fetch(base+'/sitemap.xml');
  assert.match(sitemap.headers.get('content-type'), /^application\/xml/);
  assert.match(await sitemap.text(), /<loc>https:\/\/www\.likithasports\.in\/services\/athletic-track<\/loc>/);
  assert.match(await (await fetch(base+'/robots.txt')).text(), /Sitemap: https:\/\/www\.likithasports\.in\/sitemap\.xml/);
  for (const name of ['basketball.webp','tennis.webp','football-truf.webp','pickleball.webp']) {
    const asset = await fetch(base+'/service-photos/'+name);
    assert.equal(asset.status,200);
    assert.equal(asset.headers.get('content-type'),'image/webp');
  }
  const password = require('node:crypto').randomUUID();
  assert.equal((await post('setup',{password})).status,201);
  const login = await post('login',{password});
  assert.equal(login.status,200);
  cookie = login.headers.get('set-cookie').split(';')[0];
  csrf = (await login.json()).csrf;
  const data = await (await fetch(base+'/api/admin/content',{headers:{cookie}})).json();
  assert.equal((await post('upload',{data:Buffer.from('invalid').toString('base64')})).status,400);
  const file = await fs.readFile(path.join(__dirname,'../assets/logo-transparent.png'));
  const upload = await post('upload',{data:file.toString('base64')});
  assert.equal(upload.status,201);
  const {url} = await upload.json();
  assert.deepEqual(Buffer.from(await (await fetch(base+url)).arrayBuffer()),file);
  const projectUpload = await post('upload',{data:file.toString('base64'),destination:'projects'});
  assert.equal(projectUpload.status,201);
  const projectImage = await projectUpload.json();
  const projectBytes = Buffer.from(await (await fetch(base+projectImage.url)).arrayBuffer());
  const {width,height} = await require('sharp')(projectBytes).metadata();
  assert.deepEqual([width,height],[500,500]);
  data.galleries.projects = [{image:url,alt:'Published project'}];
  data.projects = [{title:'Shuttle Cort',description:'Court project',photos:[
    {image:projectImage.url,alt:'First court photo'}, {image:url,alt:'Second court photo'}
  ]}];
  assert.equal(data.aboutCards.length,6);
  data.aboutCards[3] = {image:url,alt:'Court build',title:'Our team',designation:'Coach',description:'Site team'};
  assert.equal(data.teamCards.length,6);
  assert.equal(data.boardCards.length,3);
  data.boardCards[1] = {image:url,alt:'Board photo',title:'Board profile',designation:'Director',description:'Board biography'};
  assert.equal(data.staffCards.length,3);
  data.staffCards[2] = {image:url,alt:'Staff photo',title:'Staff profile',designation:'Coach',description:'Coordinates training.'};
  data.teamCards[0] = {image:url,alt:'Team photo',title:'Team profile',designation:'Project Lead',description:'Oversees <court> installation.'};
  data.pageIntros.clients.description = 'Published client introduction';
  data.entries.clients = [{name:'Example school', description:'Outdoor court', image:url, alt:'School court'}];
  data.entries.testimonials = [{name:'Example partner', description:'Excellent <work>', image:null, alt:''}];
  data.hero.line1 = 'Published headline';
  const publish = await post('content',data);
  assert.equal(publish.status,200);
  assert.equal((await post('content',data)).status,409);
  const home = await (await fetch(base+'/')).text();
  assert.match(home, /Published headline/);
  assert.ok(home.indexOf('id="home-projects"') > home.indexOf('id="service-cards"'));
  assert.match(home, /aria-label="Scrolling projects"/);
  assert.ok(home.includes(projectImage.url) && home.includes('First court photo') && home.includes('Published project'));
  assert.match(home, /data-home-project-slideshow tabindex/);
  assert.match(home, /Shuttle Court/);
  assert.match(home, /rel="canonical" href="https:\/\/www\.likithasports\.in\/"/);
  const projects = await (await fetch(base+'/projects')).text();
  assert.match(projects, /Published project/);
  assert.match(projects, /Police Sports Complex, Rajahmundry/);
  assert.match(await (await fetch(base+'/clients')).text(), /SP Office, Rajahmundry/);
  const clients = await (await fetch(base+'/clients')).text();
  assert.ok(clients.includes('Published client introduction') && clients.includes('Example school') && clients.includes(url));
  const testimonials = await (await fetch(base+'/testimonials')).text();
  assert.match(testimonials, /Excellent &lt;work&gt;/);
  assert.doesNotMatch(testimonials, /We will share genuine client feedback/);
  const about = await (await fetch(base+'/about-us')).text();
  assert.match(about, /Our story/);
  assert.match(about, /Nimmagadda Sports Foundation/);
  assert.match(about, /sreedattasports2007@gmail.com/);
  const team = await (await fetch(base+'/team')).text();
  assert.match(team, /<h3>Team profile<\/h3>/);
  assert.match(team, /Project Lead/);
  assert.match(team, /Oversees &lt;court&gt; installation/);
  assert.match(team, /aria-controls="management-description-1"/);
  assert.match(team, /aria-controls="team-description-3"/);
  assert.match(team, /<h3>Staff profile<\/h3>/);
  assert.ok(team.includes(url));
  assert.doesNotMatch(about, /Team profile/);
  const saved = await (await fetch(base+'/api/admin/content',{headers:{cookie}})).json();
  assert.deepEqual(saved.aboutCards[3],data.aboutCards[3]);
  assert.match(team, /aria-controls="board-description-2"/);
  assert.deepEqual(saved.boardCards[1],data.boardCards[1]);
  assert.deepEqual(saved.staffCards[2],data.staffCards[2]);
  assert.deepEqual(saved.teamCards[0],data.teamCards[0]);
  assert.equal(saved.aboutProfileIndexes.length,6);
  assert.equal(saved.aboutProfileIndexes[0],3);
  assert.equal((await post('logout',{})).status,200);
});
